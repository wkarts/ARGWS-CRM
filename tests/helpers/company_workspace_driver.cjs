'use strict';
// Test navigation adapter, not an application hook. It opens the SAME visible tab/button
// a user must choose before interacting with a control in a presentation-only panel.
// No style/hidden mutation, token replacement, network request or permission bypass.
const wrapped = new WeakSet();
const actions = ['click', 'dblclick', 'fill', 'clear', 'check', 'uncheck', 'setChecked', 'selectOption', 'setInputFiles', 'press', 'pressSequentially', 'type', 'focus'];
const factories = ['locator', 'getByRole', 'getByText', 'getByLabel', 'getByPlaceholder', 'getByTestId', 'getByTitle', 'getByAltText', 'filter', 'first', 'last', 'nth', 'and', 'or'];

async function revealWorkspaceControl(page, locator) {
    // Preserve Playwright strictness and unauthorized/missing-control failures.
    if (await locator.count() !== 1) return;
    const panelIds = await locator.evaluate(element => {
        const ids = [];
        for (let node = element.parentElement; node; node = node.parentElement) {
            if (node.matches('.company-workspace-panel[hidden]') && node.closest('[data-company-workspace]')) ids.unshift(node.id);
        }
        return ids;
    });
    for (const id of panelIds) {
        // IDs are generated by company-workspace.js, not provider/user HTML.
        if (!/^company-workspace-\d+-\d+$/.test(id)) throw new Error('Unexpected workspace panel ID');
        const button = page.locator('[data-company-workspace] button[aria-controls="' + id + '"]');
        await button.click();
    }
}

function wrapLocator(page, locator) {
    if (wrapped.has(locator)) return locator;
    wrapped.add(locator);
    for (const name of actions) {
        if (typeof locator[name] !== 'function') continue;
        const original = locator[name].bind(locator);
        locator[name] = async (...args) => {
            await revealWorkspaceControl(page, locator);
            return original(...args);
        };
    }
    for (const name of factories) {
        if (typeof locator[name] !== 'function') continue;
        const original = locator[name].bind(locator);
        locator[name] = (...args) => wrapLocator(page, original(...args));
    }
    return locator;
}

function installCompanyWorkspaceDriver(page) {
    if (wrapped.has(page)) return page;
    wrapped.add(page);
    for (const name of factories) {
        if (typeof page[name] !== 'function') continue;
        const original = page[name].bind(page);
        page[name] = (...args) => wrapLocator(page, original(...args));
    }
    for (const name of actions) {
        if (typeof page[name] !== 'function') continue;
        const original = page[name].bind(page);
        page[name] = async (selector, ...args) => {
            await revealWorkspaceControl(page, page.locator(selector));
            return original(selector, ...args);
        };
    }
    return page;
}
async function workspacePage(context, options) {
    return installCompanyWorkspaceDriver(await context.newPage(options));
}
module.exports = { workspacePage, installCompanyWorkspaceDriver, revealWorkspaceControl };
